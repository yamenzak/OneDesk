def missing() -> list[str]:
	gone = []
	for what, _why, _ours, where, line in OVERRIDES:
		path = BENCH / where
		if not path.exists():
			gone.append(f"{what}: {where} is not in the checkout")
		elif line not in path.read_text():
			gone.append(f"{what}: {where} no longer contains {line!r}")
	return gone


def page() -> str:
	out = [HEADER, "# What we override, and what it leans on\n"]
	out.append(
		"\nEach row is something that would still run but stop working if upstream moved."
		" `python scripts/overrides.py --check` fails when the line in the last column is"
		" gone, which is the point of the table.\n"
	)
	out.append("\n| What | Why | Ours | Upstream | Must still contain |\n")
	out.append("|---|---|---|---|---|\n")
	for what, why, ours, where, line in OVERRIDES:
		out.append(f"| {what} | {why} | `{ours}` | `{where}` | `{line}` |\n")
	out.append(f"\n{len(OVERRIDES)} overrides.\n")
	return "".join(out)


def main() -> int:
	where = tree.ROOT / "docs" / "OVERRIDES.md"
	if "--check" in sys.argv:
		gone = missing()
		if gone:
			print("upstream moved under us:\n  " + "\n  ".join(gone))
			return 1
		want = page()
		if not where.exists() or where.read_text() != want:
			print("docs/OVERRIDES.md is stale. Run `python scripts/overrides.py`.")
			return 1
		return 0
	where.write_text(page())
	print(f"wrote {where.relative_to(tree.ROOT)} ({len(OVERRIDES)} overrides)")
	return 0


if __name__ == "__main__":
	sys.exit(main())
