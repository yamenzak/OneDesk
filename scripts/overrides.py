"""Everything One does that leans on something frappe, erpnext or hrms owns.

Not a changelog: a changelog goes stale and nothing notices. Each row names the
upstream line it depends on, and `--check` fails when that line is gone, so a
`bench update` that moves it breaks a test instead of a screen.

A row belongs here when our code would still run but stop working if upstream
changed — a CSS rule we outweigh, a class we subclass, a seam we hook, a field
we write. Ordinary use of a documented API does not.

    python scripts/overrides.py           write docs/OVERRIDES.md
    python scripts/overrides.py --check   fail if any upstream line is gone
"""

