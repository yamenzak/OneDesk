DOCS = tree.ROOT / "docs"

DESK_RECORDS = ("workspace", "dock", "desktop_icon", "custom_sidebar", "sidebar", "role")

HEADER = "<!-- generated by scripts/docs.py — do not edit -->\n"


def doctypes() -> dict[str, list[dict]]:
	found: dict[str, list[dict]] = {}
	for path in tree.fixtures():
		if path.parent.parent.name != "doctype" or path.stem != path.parent.name:
			continue
		spec = json.loads(path.read_text())
		module = spec.get("module", "?")
		found.setdefault(module, []).append(
			{
				"name": spec["name"],
				"fields": len(spec.get("fields", [])),
				"child": bool(spec.get("istable")),
				"single": bool(spec.get("issingle")),
				"submittable": bool(spec.get("is_submittable")),
			}
		)
	return found


def desk_records() -> dict[str, list[str]]:
	found: dict[str, list[str]] = {}
	for path in tree.fixtures():
		parts = path.parts
		for kind in DESK_RECORDS:
			if kind in parts:
				found.setdefault(kind, []).append(path.stem)
	return found


def whitelisted() -> list[str]:
	found = []
	for path in tree.python():
		text = path.read_text()
		if "@frappe.whitelist" not in text:
			continue
		lines = text.splitlines()
		for i, line in enumerate(lines):
			if "@frappe.whitelist" not in line:
				continue
			for after in lines[i + 1 : i + 4]:
				if after.lstrip().startswith("def "):
					name = after.split("def ", 1)[1].split("(", 1)[0]
					dotted = str(path.relative_to(tree.ROOT).with_suffix("")).replace("/", ".")
					found.append(f"{dotted}.{name}")
					break
	return sorted(found)


def modules_page() -> str:
	types = doctypes()
	records = desk_records()
	out = [HEADER, "# Modules\n"]
	for module in tree.modules():
		where = tree.module_dir(module)
		out.append(f"\n## {module}\n")
		out.append(f"\n`{where.relative_to(tree.ROOT)}`\n")
		owned = sorted(types.get(module, []), key=lambda d: d["name"])
		if owned:
			out.append("\n| Doctype | Fields | Kind |\n|---|--:|---|\n")
			for d in owned:
				kind = ", ".join(
					k for k, on in
					(("child", d["child"]), ("single", d["single"]), ("submittable", d["submittable"]))
					if on
				) or "document"
				out.append(f"| {d['name']} | {d['fields']} | {kind} |\n")
		else:
			out.append("\nNo doctypes yet.\n")

	out.append("\n## Desk records shipped as fixtures\n")
	if records:
		out.append("\n")
		for kind in sorted(records):
			out.append(f"* **{kind}** — {', '.join(sorted(records[kind]))}\n")
	else:
		out.append("\nNone yet.\n")

	methods = whitelisted()
	out.append("\n## Whitelisted methods\n")
	out.append("\n" + ("".join(f"* `{m}`\n" for m in methods) if methods else "None yet.\n"))
	return "".join(out)


def _rules(number: int) -> list[str]:
	return [guard.id for guard in GUARDS if guard.point == number]


def registry_page() -> str:
	"""Where each module on its way to ready stands on the points it is held
	to before live (docs/STANDARD.md): how many rules hold each, and the looks
	a person gives what no rule can settle."""
	out = [
		HEADER,
		"# Registry\n",
		"\nThe points of docs/STANDARD.md a module is held to before live, for each module on its way to ready."
		" Each point's rules are in docs/STANDARD-RULES.md.\n",
	]
	for module, spec in ready.MODULES.items():
		out.append(f"\n## {module} {ready.current(module) or ''}\n")
		out.append(f"\n{'Ready.' if spec.get('ready') else 'Not marked ready yet.'}\n")
		out.append("\n| Point | Rules | Last looked at |\n|---|--:|---|\n")
		for one in ready.registry(module):
			said = one["checked"]
			looked = f"in {said['version']}" if said else "not yet" if one["look"] else "—"
			out.append(f"| {one['number']}. {one['title']} | {len(_rules(one['number']))} | {looked} |\n")
		looks = [one for one in ready.registry(module) if one["look"]]
		out.append("\nWhat a person looks at:\n\n")
		out += [f"- **{one['title']}**: {one['look']}.\n" for one in looks]
	out.append(switchovers_section())
	return "".join(out)


def standard_rules_page() -> str:
	"""What holds each point of docs/STANDARD.md: its rules, by id, with what
	each fails on and where it runs (tests/guards/registry.py), and the look a
	person gives where no rule can settle it (onedesk/one/standard.py)."""
	out = [
		HEADER,
		"# The standard's rules\n",
		"\nWhat holds each point of docs/STANDARD.md. `python3 scripts/lint.py --point N` lists the same.\n",
	]
	for group in standard.GROUPS:
		out.append(f"\n## {group}\n")
		for point in standard.POINTS.values():
			if point.group != group:
				continue
			out.append(f"\n### {point.number}. {point.title}\n\n")
			if point.live:
				out.append("A module is held to it before it is marked ready.\n\n")
			if point.look:
				out.append(f"A person looks: {point.look}.\n\n")
			out += [f"- `{guard.id}`: {guard.what} (`{guard.runs}`)\n" for guard in GUARDS if guard.point == point.number]
			if point.number in PLANNED:
				out.append(f"- coming: {PLANNED[point.number]}\n")
	return "".join(out)


def switchovers_section() -> str:
	"""Every change One can't work without that runs the old way until its
	day (trust_center/switchovers.py), so both ways come out once it has taken
	effect: what it does, the day, and the day it is due to be cleaned up."""
	from onedesk.trust_center import switchovers

	out = [
		"\n## Switchovers\n",
		"\nChanges One can't work without, announced ahead in the agreements. The old way"
		" runs until the day, the new way from it, and both stay in the code until the"
		" clean-up day, when the guard asks for the old way to go.\n",
	]
	rows = switchovers.all_of()
	if not rows:
		return "".join(out) + "\nNone now.\n"
	out.append("\n| Switchover | Module | Does | Takes effect | Clean up by |\n|---|---|---|---|---|\n")
	out += [f"| `{one['key']}` | {one['module']} | {one['does']} | {one['effective']} | {one['clean_by']} |\n" for one in rows]
	return "".join(out)


def upstream_page() -> str:
	record = json.loads((tree.ROOT / "upstream.json").read_text())
	out = [HEADER, "# Upstream\n"]
	out.append(
		"\nOne runs on frappe, erpnext and hrms as they are on their develop branches,"
		" and keeps up with them one checkpoint at a time. A checkpoint is the three"
		" apps at known commits, with a note in `docs/upstream/` that went through"
		" everything that changed since the last one.\n"
	)
	out.append(f"\n## Now\n\nCheckpoint of {record['recorded_on']}")
	out.append(f", reviewed in `{record['note']}`.\n" if record.get("note") else ".\n")
	out.append("\n| App | Version | Commit | Dated |\n|---|---|---|---|\n")
	for app in ("frappe", "erpnext", "hrms"):
		if app in record:
			one = record[app]
			out.append(f"| {app} | {one.get('version', '?')} | `{one['sha'][:10]}` | {one['date']} |\n")
	out.append(
		"\n## Taking the next checkpoint\n\n"
		"1. `python scripts/upstream.py --fetch` brings in each app's upstream branch,"
		" and `python scripts/upstream.py` says what landed.\n"
		"2. `--draft` writes `docs/upstream/<today>.md`. It lists every place One leans"
		" on upstream that moved (a line `scripts/overrides.py` names, a doctype we"
		" customize or hook, a method we override, a desk method our scripts patch,"
		" the frappe/ui parts the islands use) and everything upstream shipped (each"
		" `feat` commit, new doctypes, new hooks, new frappe/ui parts). Every item"
		" starts open.\n"
		"3. `--update` backs up every site (or `ONE_SITE`), moves each app to the note's commits, installs"
		" what they need, migrates and builds, as the bench's user. `ONE_BENCH_ENV`"
		" names a file it sources before each step, with the Node, certificate bundle and"
		" proxy the machine needs and the bench does not carry."
		" Restart the bench after it.\n"
		"4. Run `scripts/overrides.py --check`, the gates, the browser screens and the"
		" demo checks (a fresh install and demo build is the surest), and fix what"
		" broke. Then `python scripts/atlas.py --snapshot` and `--brand`: a record type,"
		" report or page upstream added fails `tests/guards/test_atlas.py` until it is"
		" placed or answered (docs/ATLAS.md), and a new sentence naming ERPNext or"
		" Frappe is said as One.\n"
		"5. Close every item in the note: tick it and say, after a dash, what was done:"
		" **Kept** (still right as it is), **Corrected** (we changed ours to follow),"
		" **Adopted** (we now use what upstream added), **Not for us**, or **Later**"
		" with the task it went to.\n"
		"6. `--checkpoint` records it in `upstream.json`. It refuses while the bench is"
		" not at the note's commits or any item is open.\n"
		"\nThe gates fail when the bench moved without a checkpoint, when the"
		" checkpoint's note has an open item, or when the checkpoint is more than"
		" 14 days old. So the bench cannot drift, and falling behind stops the gates.\n"
	)
	history = record.get("history") or []
	if history:
		out.append("\n## Before\n\n| Checkpoint | frappe | erpnext | hrms | Note |\n|---|---|---|---|---|\n")
		for one in reversed(history):
			cells = [f"`{one[app]['sha'][:10]}` {one[app]['date']}" if app in one else "" for app in ("frappe", "erpnext", "hrms")]
			out.append(f"| {one.get('recorded_on', '?')} | {' | '.join(cells)} | {one.get('note') or 'none'} |\n")
	return "".join(out)


def _now() -> str:
	return datetime.now().strftime("%Y-%m-%d %H:%M:%S.%f")


def dock_fixture() -> str:
	"""The Dock One ships: a row for each app with a place on the rail, in the
	rail's order, from the manifests (onedesk/one/registry). Its `modified`
	moves when its rows do, so a migrate takes them."""
	path = tree.APP / "dock" / "onedesk" / "onedesk.json"
	shipped = json.loads(path.read_text())
	rows = [
		{"added": 0, "hidden": 0, "icon": app.mark, "link_to": app.sidebar, "link_type": "Sidebar", "title": app.name}
		for app in registry.apps()
		if app.rail is not None
	]
	if shipped["items"] != rows:
		shipped["items"], shipped["modified"] = rows, _now()
	return json.dumps(shipped, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def named_fixture(path: Path):
	"""A synced record with its labels that are an app's name written from
	the registry (onedesk/one/registry/labels.py), in place, and its
	`modified` moved when one changed."""
	mine = [one for one in labels.named(tree.APP) if tree.APP / one.file == path]

	def build() -> str:
		text = path.read_text(encoding="utf-8")
		record = json.loads(text)
		moved = False
		for one in mine:
			was, want = labels.holder(record, one).get(one.field), labels.wanted(one)
			if was == want:
				continue
			said = f'"{one.field}": {json.dumps(was, ensure_ascii=False)}'
			if text.count(said) != 1:
				raise ValueError(f"{one.file}: {said} is there {text.count(said)} times, not once")
			text, moved = text.replace(said, f'"{one.field}": {json.dumps(want, ensure_ascii=False)}'), True
		if moved:
			text = text.replace(f'"modified": "{record["modified"]}"', f'"modified": "{_now()}"', 1)
		return text

	return build


def modules_txt() -> str:
	"""frappe's list of One's modules: each manifest's module, in the rail's order."""
	return "".join(f"{app.module}\n" for app in registry.apps() if app.module)


PAGES = {
	tree.APP / "dock" / "onedesk" / "onedesk.json": dock_fixture,
	tree.APP / "modules.txt": modules_txt,
	DOCS / "MODULES.md": modules_page,
	DOCS / "UPSTREAM.md": upstream_page,
	DOCS / "REGISTRY.md": registry_page,
	DOCS / "STANDARD-RULES.md": standard_rules_page,
	DOCS / "ATLAS.md": atlas.page,
	atlas.SHOWN: atlas.shown_json,
	**{tree.APP / file: named_fixture(tree.APP / file) for file in dict.fromkeys(one.file for one in labels.named(tree.APP))},
}


def stale() -> list[str]:
	"""Each generated file that is not what its builder makes now."""
	return [
		str(where.relative_to(tree.ROOT)) for where, build in PAGES.items() if not where.exists() or where.read_text() != build()
	]


def main() -> int:
	args = argparse.ArgumentParser()
	args.add_argument("--check", action="store_true")
	opts = args.parse_args()

	if opts.check:
		found = stale()
		if found:
			print(f"stale: {', '.join(found)}. Run `python scripts/docs.py`.")
		return 1 if found else 0
	DOCS.mkdir(exist_ok=True)
	for where, build in PAGES.items():
		where.write_text(build())
	print(f"wrote {', '.join(str(where.relative_to(tree.ROOT)) for where in PAGES)}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
