"""Every string our POT carries reaches a reader of Arabic or German.

`onedesk/locale/main.pot` is generated by `bench generate-pot-file --app onedesk`
and carries every label, description, Select option and `_()` string this app
puts on a screen — including the ones whose text frappe, erpnext or hrms already
say somewhere of their own.

Those we leave with an empty `msgstr`. Babel omits an empty entry from the
compiled MO, and `get_translations_from_apps` merges every installed app's
catalogue, so "Salary Slip" resolves from hrms's translation rather than a
second copy of it in ours. What we do translate is our own strings, plus the
handful upstream leaves blank or says in the wrong sense — "Leave" as the verb
where our rail means the noun. Ours wins there because onedesk is installed
last and its MO is merged last.

Which makes this the other half of `docs/WORDING.md`: rewording a label is also
a translation change, and forgetting the second half fails here rather than in
front of somebody reading the form in Arabic.
"""

import re
from pathlib import Path

import pytest
from tests.bench import APPS

ROOT = Path(__file__).resolve().parents[2]
LOCALE = ROOT / "onedesk" / "locale"
BENCH = APPS

SHIPPED = ("ar", "de")

UPSTREAM = ("frappe", "erpnext", "hrms")

ENTRY = re.compile(r"^msgid ((?:\"[^\n]*\"\n)+)msgstr ((?:\"[^\n]*\"\n?)+)", re.M)
QUOTED = re.compile(r"\"((?:[^\"\\]|\\.)*)\"")


def read(path: Path) -> dict[str, str]:
	if not path.exists():
		return {}
	found = {}
	for match in ENTRY.finditer(path.read_text(encoding="utf-8")):
		msgid = "".join(QUOTED.findall(match.group(1)))
		if msgid:
			found[msgid] = "".join(QUOTED.findall(match.group(2)))
	return found


def upstream(lang: str) -> dict[str, str]:
	found = {}
	for app in UPSTREAM:
		for msgid, msgstr in read(BENCH / app / app / "locale" / f"{lang}.po").items():
			if msgstr:
				found.setdefault(msgid, msgstr)
	return found


def pot_missing(locale: Path) -> bool:
	return not (locale / "main.pot").exists()


def test_the_pot_exists():
	assert not pot_missing(LOCALE), "run bench generate-pot-file --app onedesk"


def untranslated(pot: dict, ours: dict, theirs: dict) -> list[str]:
	"""The POT's strings neither we nor an installed app translate. Pure."""
	return sorted(msgid for msgid in pot if not ours.get(msgid) and not theirs.get(msgid))


@pytest.mark.parametrize("lang", SHIPPED)
def test_every_string_reaches_a_reader(lang):
	missing = untranslated(read(LOCALE / "main.pot"), read(LOCALE / f"{lang}.po"), upstream(lang))
	assert not missing, (
		f"{lang}.po leaves these untranslated and no installed app translates them:\n  "
		+ "\n  ".join(missing)
	)


def unsaid(pot: dict, ours: dict) -> list[str]:
	"""What we translate that the POT no longer says. Pure."""
	return sorted(msgid for msgid, msgstr in ours.items() if msgstr and msgid not in pot)


@pytest.mark.parametrize("lang", SHIPPED)
def test_nothing_is_translated_that_is_not_said(lang):
	"""A msgid left behind by a reworded label is a translation nobody reads."""
	stale = unsaid(read(LOCALE / "main.pot"), read(LOCALE / f"{lang}.po"))
	assert not stale, f"{lang}.po translates strings no longer in the POT:\n  " + "\n  ".join(stale)


def lost_placeholders(ours: dict) -> list[str]:
	"""The translations whose placeholders differ from their English. Pure."""
	return [msgid for msgid, msgstr in ours.items() if msgstr and set(re.findall(r"\{\w*\}", msgid)) != set(re.findall(r"\{\w*\}", msgstr))]


@pytest.mark.parametrize("lang", SHIPPED)
def test_placeholders_survive_translation(lang):
	"""{0} in the English has to be {0} in the translation, or format() raises."""
	wrong = lost_placeholders(read(LOCALE / f"{lang}.po"))
	assert not wrong, f"{lang}.po loses or invents placeholders in:\n  " + "\n  ".join(wrong)


SAID = re.compile(r'__\(\s*"((?:[^"\\]|\\.)*)"\s*\)')


def unextracted(source: str) -> list[str]:
	"""Each plain `__("...")` in a script that frappe's extractor, which
	writes the POT, does not find. A `//` in a template nested inside another
	(a URL) throws its lexer off, and what follows reaches no reader."""
	from io import BytesIO

	from frappe.gettext.extractors.javascript import extract

	found = {one[2] if isinstance(one[2], str) else one[2][0] for one in extract(BytesIO(source.encode()), ["__"], [], {})}
	return [one for one in SAID.findall(source) if one not in found]


def test_every_desk_string_is_extracted():
	missed = {
		str(path.relative_to(ROOT)): left
		for path in sorted((ROOT / "onedesk" / "public" / "js").rglob("*.js"))
		if (left := unextracted(path.read_text(encoding="utf-8")))
	}
	assert not missed, missed


def test_the_translation_rules_catch_their_examples(tmp_path):
	assert pot_missing(tmp_path)
	(tmp_path / "ar.po").write_text('msgid "Leave"\nmsgstr "إجازة"\n\nmsgid "Gone"\nmsgstr "ذهب"\n\nmsgid "Hi {0}"\nmsgstr "مرحبا"\n', encoding="utf-8")
	ours = read(tmp_path / "ar.po")
	assert ours["Leave"] == "إجازة"
	pot = {"Leave": "", "Hi {0}": "", "New": ""}
	assert untranslated(pot, ours, {}) == ["New"]
	assert untranslated(pot, ours, {"New": "جديد"}) == []
	assert unsaid(pot, ours) == ["Gone"]
	assert lost_placeholders(ours) == ["Hi {0}"]
	assert lost_placeholders({"Hi {0}": "مرحبا {0}"}) == []
	nested = 'const m = p\n\t? `<div>\n\t\t${f({ label: __("Open"), attrs: { "x": `https://${p.d}` } })}\n\t</div>`\n\t: "";\nh(__("Lost") + `<i></i>`);\n'
	assert unextracted(nested) == ["Open", "Lost"]
	assert unextracted(nested.replace("`https://${p.d}`", '"https://" + p.d')) == []
